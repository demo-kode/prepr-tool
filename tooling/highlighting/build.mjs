import { build } from 'esbuild';
import { bundledLanguagesInfo } from 'shiki/langs';
import { extraLanguages } from '../../static/extra-grammars.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('.', import.meta.url)));
const output = '../../static/vendor';
await mkdir(output, { recursive: true });
const result = await build({ absWorkingDir: process.cwd(), entryPoints: ['entry.mjs'], outfile: `${output}/shiki.js`,
  bundle: true, minify: true, format: 'esm', platform: 'browser', target: 'es2022',
  legalComments: 'eof', metafile: true });
await writeFile('../../static/languages.js', '// Generated by tooling/highlighting/build.mjs.\n' +
  `globalThis.PreprLanguages = ${JSON.stringify([...bundledLanguagesInfo, ...extraLanguages])};\n`);
const packages = new Set();
for (const path of Object.keys(result.metafile.inputs)) {
  const match = path.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
let notice = '# Bundled syntax highlighter licenses\n\nGenerated from pinned npm packages.\n';
for (const name of [...packages].sort()) {
  const pkg = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
  let license;
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
    try { license = await readFile(`node_modules/${name}/${file}`, 'utf8'); break; } catch {}
  }
  if (!license) throw Error(`Missing license: ${name}`);
  notice += `\n## ${name} ${pkg.version}\n\n${license}\n`;
}
await writeFile(`${output}/LICENSES.txt`, notice);
console.log(`Bundled Shiki; ${bundledLanguagesInfo.length} languages, ${packages.size} licensed packages.`);
